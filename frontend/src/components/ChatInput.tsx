import React, { useState, useRef, useEffect } from "react";
import { Send, Loader2 } from "lucide-react";

interface ChatInputProps {
  onSendMessage: (message: string) => void;
  isLoading: boolean;
  disabled?: boolean;
}

export const ChatInput: React.FC<ChatInputProps> = ({
  onSendMessage,
  isLoading,
  disabled = false,
}) => {
  const [text, setText] = useState("");
  const textareaRef = useRef<HTMLTextAreaElement>(null);

  // Auto-resize textarea
  useEffect(() => {
    if (textareaRef.current) {
      textareaRef.current.style.height = "auto";
      const scrollHeight = textareaRef.current.scrollHeight;
      // Max height approx 140px (about 5-6 lines)
      textareaRef.current.style.height = `${Math.min(scrollHeight, 140)}px`;
    }
  }, [text]);

  const handleSubmit = (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    const trimmed = text.trim();
    if (!trimmed || isLoading || disabled) return;

    onSendMessage(trimmed);
    setText("");

    if (textareaRef.current) {
      textareaRef.current.style.height = "auto";
    }
  };

  const handleKeyDown = (e: React.KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      handleSubmit();
    }
  };

  const isSendDisabled = !text.trim() || isLoading || disabled;

  return (
    <div className="chat-input-wrapper">
      <form onSubmit={handleSubmit} className="input-form">
        <div className="input-box-container">
          <textarea
            ref={textareaRef}
            value={text}
            onChange={(e) => setText(e.target.value)}
            onKeyDown={handleKeyDown}
            placeholder="Ask anything about farmer records..."
            disabled={disabled}
            rows={1}
            className="chat-textarea"
          />
          <button
            type="submit"
            disabled={isSendDisabled}
            className={`send-button ${isSendDisabled ? "disabled" : "active"}`}
            title="Send message"
            aria-label="Send message"
          >
            {isLoading ? (
              <Loader2 size={18} className="spinner-icon" />
            ) : (
              <Send size={18} />
            )}
          </button>
        </div>
      </form>
      <div className="input-disclaimer">
        <span>Answers are generated by AI from the available database records.</span>
      </div>
    </div>
  );
};
